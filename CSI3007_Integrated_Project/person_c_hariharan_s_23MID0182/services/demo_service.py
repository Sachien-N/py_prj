DEMO_SOCKETS = [
    ("Demo · Living room AC", "Split air conditioner", Decimal("1500"), "Living room"),
    ("Demo · Refrigerator", "Refrigerator", Decimal("180"), "Kitchen"),
    ("Demo · Work desk", "Computer and monitor", Decimal("320"), "Study"),
]


def _shift_month_start(value: date, months: int) -> date:
    index = value.year * 12 + value.month - 1 + months
    year, month_index = divmod(index, 12)
    return date(year, month_index + 1, 1)


def _power_for(appliance: str, rated: float, hour: int, socket_id: int) -> float:
    appliance = appliance.lower()
    if "air" in appliance:
        wave = (math.sin((hour - 13) / 24 * 2 * math.pi) + 1) / 2
        factor = 0.25 + 0.65 * wave
    elif "fridge" in appliance or "refrigerator" in appliance:
        factor = 0.28 + 0.10 * (1 if hour in (2, 3, 8, 9, 14, 15, 20, 21) else 0)
    else:
        factor = 0.06 + 0.45 * max(0, math.sin((hour - 8) / 24 * 2 * math.pi))
    return max(0.0, min(rated, rated * factor + socket_id * 1.3))


def seed_demo(db: Session, *, months: int = 6, force: bool = False) -> dict:
    if months < 1 or months > 12:
        raise AppError("months must be between 1 and 12", status_code=422)
    if force:
        demo_bills = list(
            db.scalars(
                select(ElectricityBill).where(
                    ElectricityBill.bill_reference.like("DEMO-%")
                )
            ).all()
        )
        for bill in demo_bills:
            db.delete(bill)
        demo_sockets = list(
            db.scalars(select(Socket).where(Socket.is_demo.is_(True))).all()
        )
        for socket in demo_sockets:
            db.delete(socket)
        db.commit()

    sockets = []
    for name, appliance, rated, location in DEMO_SOCKETS:
        socket = db.scalar(select(Socket).where(Socket.name == name))
        if not socket:
            socket = Socket(
                name=name,
                appliance=appliance,
                rated_power_w=rated,
                location=location,
                is_active=True,
                adapter_type="simulated",
                is_demo=True,
            )
            db.add(socket)
            db.flush()
        sockets.append(socket)
    db.commit()

    today_local = datetime.now(settings.timezone).date()
    start_month = _shift_month_start(today_local.replace(day=1), -months)
    start_local = datetime.combine(start_month, time.min, tzinfo=settings.timezone)
    end_local = datetime.now(settings.timezone).replace(minute=0, second=0, microsecond=0)
    created_readings = 0
    for socket in sockets:
        existing = set(
            db.scalars(
                select(ElectricityReading.reading_at).where(
                    ElectricityReading.socket_id == socket.id
                )
            ).all()
        )
        current = start_local
        while current < end_local:
            stored = to_naive_utc(current)
            if stored not in existing:
                power = _power_for(
                    socket.appliance, float(socket.rated_power_w), current.hour, socket.id
                )
                db.add(
                    ElectricityReading(
                        socket_id=socket.id,
                        reading_at=stored,
                        power_w=Decimal(str(round(power, 2))),
                        source="simulated",
                        is_simulated=True,
                        quality_flag="ok",
                        out_of_order=False,
                        notes="SIMULATED demo reading generated by the project",
                    )
                )
                created_readings += 1
            current += timedelta(hours=1)
        db.commit()

    created_bills = 0
    current_month_start = today_local.replace(day=1)
    for offset in range(months, 0, -1):
        month_start = _shift_month_start(current_month_start, -offset)
        month_end = date(
            month_start.year,
            month_start.month,
            calendar.monthrange(month_start.year, month_start.month)[1],
        )
        reference = f"DEMO-{month_start.strftime('%Y-%m')}"
        if db.scalar(
            select(ElectricityBill).where(ElectricityBill.bill_reference == reference)
        ):
            continue
        aggregate = aggregate_range(db, month_start, month_end)
        if aggregate["interval_segments"] == 0:
            continue
        units = dec(aggregate["energy_kwh"])
        try:
            tariff = select_tariff(db, month_end, "domestic")
            estimate = calculate_estimate(
                db,
                units=units,
                on_date=month_end,
                category=tariff.category,
                tariff_id=tariff.id,
            )
        except AppError:
            continue
        factor = Decimal("1.15") if month_start.month in (5, 6) else Decimal("1.01")
        billed_units = (units * factor).quantize(Decimal("0.01"))
        amount = (dec(estimate["total_cost"]) * factor).quantize(Decimal("0.01"))
        db.add(
            ElectricityBill(
                bill_reference=reference,
                billing_period_start=month_start,
                billing_period_end=month_end,
                billed_units=billed_units,
                bill_amount=money(amount),
                fixed_charges=Decimal("0"),
                other_charges=Decimal("0"),
                bill_date=month_end,
                source="SIMULATED DEMO — not a real TNEB bill",
                notes=(
                    "Generated demonstration bill. It is not a real utility bill and must not "
                    "be presented as one."
                ),
            )
        )
        created_bills += 1
    db.commit()
    return {
        "simulated": True,
        "sockets": len(sockets),
        "readings_created": created_readings,
        "bills_created": created_bills,
        "months_requested": months,
        "warning": (
            "All generated sockets, readings and bills are simulated demonstration data. "
            "They are not measurements or real TNEB/TANGEDCO bills."
        ),
    }
